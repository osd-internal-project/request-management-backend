/**
 * Call and webhook examples for the admin screens, cut from the OpenAPI
 * documents so they never drift from the real routes. Run after `yarn openapi`.
 *
 * Written as a TS module rather than JSON beside the service: webpack bundles
 * it, so there is no runtime file lookup to break boot (see `findCatalogue`).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';
import {
  buildApiExamples,
  buildWebhookExamples,
  type OpenApiDocument,
} from '../services/core-service/src/principal/api-examples-builder';

const TARGET = join(
  'services',
  'core-service',
  'src',
  'principal',
  'api-examples.generated.ts',
);

function read(file: string): OpenApiDocument {
  return JSON.parse(
    readFileSync(join('docs', 'openapi', file), 'utf8'),
  ) as OpenApiDocument; // our own generator's output
}

async function main(): Promise<void> {
  const api = buildApiExamples(read('external-service.json'));
  const webhooks = buildWebhookExamples(read('external-webhook.json'));

  const source = [
    '// Generated by `yarn openapi` (scripts/generate-examples.ts) — do not edit.',
    "import type { ApiExample, WebhookExample } from './api-examples-builder';",
    '',
    "export type { ApiExample, WebhookExample } from './api-examples-builder';",
    '',
    `export const API_EXAMPLES: readonly ApiExample[] = ${JSON.stringify(api)};`,
    '',
    `export const WEBHOOK_EXAMPLES: readonly WebhookExample[] = ${JSON.stringify(webhooks)};`,
    '',
  ].join('\n');

  const options = await resolveConfig(TARGET);
  writeFileSync(
    TARGET,
    await format(source, { ...options, parser: 'typescript' }),
  );
  console.log(
    `${TARGET}: ${api.length} call example(s), ${webhooks.length} webhook example(s)`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
